export function seedLeads(): void {
  const db = getDb();
  const now = new Date().toISOString();

  // Clear existing leads to guarantee repeatable, idempotent seed runs
  db.exec("DELETE FROM leads;");

  const insert = db.prepare(`
    INSERT INTO leads
      (id, companyName, website, industry, location, estimatedRevenue, employeeCount,
       description, leadScore, scoreTier, scoreReasons, status, notes, createdAt, updatedAt)
    VALUES
      (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
  `);

  for (let i = 0; i < syntheticLeads.length; i++) {
    const lead = syntheticLeads[i];
    const padIndex = (i + 1).toString().padStart(12, "0");
    const deterministicId = lead.id ?? `00000000-0000-4000-a000-${padIndex}`;

    insert.run([
      deterministicId,
      lead.companyName,
      lead.website,
      lead.industry,
      lead.location,
      lead.estimatedRevenue,
      lead.employeeCount,
      lead.description,
      lead.leadScore,
      lead.scoreTier,
      JSON.stringify(lead.scoreReasons),
      lead.status,
      lead.notes,
      now,
      now,
    ]);
  }
  insert.free();

  saveDb();
  console.log(`[seed] Inserted ${syntheticLeads.length} synthetic leads.`);
}

async function main() {
  await initDbConnection();
  initDb();
  seedLeads();
  const db = getDb();
  const stmt = db.prepare("SELECT COUNT(*) as n FROM leads");
  stmt.step();
  const { n } = stmt.getAsObject() as unknown as { n: number };
  stmt.free();
  console.log(`[seed] Total leads in database: ${n}`);
  closeDb();
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  main().catch((err) => {
    console.error("[seed] Failed:", err);
    process.exit(1);
  });
}
